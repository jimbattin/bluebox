import { expect, test } from "bun:test";
import {
  crc32,
  hello,
  romBegin,
  romCommit,
  romData,
  romErase,
  parseDeviceMessage,
  selectProgram,
  setBypass,
  setMix,
  setOption,
  setOutMix,
  setSlider,
} from "./protocol";

const u8 = (a: number[]) => Uint8Array.from(a);

test("host encoders", () => {
  expect(hello()).toEqual([0xf0, 0x7d, 0x42, 0x01, 0x01, 0xf7]);
  expect(selectProgram(13)).toEqual([0xf0, 0x7d, 0x42, 0x01, 0x02, 0x0d, 0xf7]);
  expect(setSlider(1, 1, 0xc0)).toEqual([0xf0, 0x7d, 0x42, 0x01, 0x03, 0x01, 0x01, 0x01, 0x40, 0xf7]);
  expect(setOption(6, true)).toEqual([0xf0, 0x7d, 0x42, 0x01, 0x04, 0x06, 0x01, 0xf7]);
  expect(setMix(16383)).toEqual([0xf0, 0x7d, 0x42, 0x01, 0x05, 0x7f, 0x7f, 0xf7]);
  expect(setBypass(true)).toEqual([0xf0, 0x7d, 0x42, 0x01, 0x06, 0x01, 0xf7]);
  expect(setOutMix(5)).toEqual([0xf0, 0x7d, 0x42, 0x01, 0x0b, 0x05, 0xf7]);
});

test("parse STATE", () => {
  const m = parseDeviceMessage(
    u8([
      0xf0, 0x7d, 0x42, 0x01, 0x10, 0x00, 0x16, 0x01, 0x01, 0x01, 0x00, 0x01, 0x40, 0x40, 0x00, 0x00, 0x35, 0x04, 0x05,
      0xf7,
    ]),
  );
  expect(m).toEqual({
    kind: "state",
    programIndex: 0,
    programCount: 22,
    programId: 0x81,
    runState: 1,
    bypass: false,
    options: 0xc0,
    mix: 8192,
    pageMask: 0x35,
    outMix: 4,
    outDefault: 5,
  });
});

test("parse PAGE", () => {
  const m = parseDeviceMessage(
    u8([
      0xf0, 0x7d, 0x42, 0x01, 0x11, 0x01, 0x01, 0x04, 0x00, 0x5f, 0x00, 0x20, 0x01, 0x36, 0x00, 0x55, 0x00, 0x00, 0xf7,
    ]),
  );
  expect(m).toEqual({ kind: "page", page: 1, values: [0x84, 0x5f, 0x20, 0xb6, 0x55, 0x00] });
});

test("parse LOG", () => {
  expect(parseDeviceMessage(u8([0xf0, 0x7d, 0x42, 0x01, 0x12, 0x68, 0x69, 0xf7]))).toEqual({ kind: "log", text: "hi" });
});

test("bad header, version, length", () => {
  expect(parseDeviceMessage(u8([0xf0, 0x7c, 0x42, 0x01, 0x12, 0x68, 0xf7]))).toBeNull();
  expect(parseDeviceMessage(u8([0xf0, 0x7d, 0x41, 0x01, 0x12, 0x68, 0xf7]))).toBeNull();
  expect(parseDeviceMessage(u8([0xf0, 0x7d, 0x42, 0x02, 0x12, 0x68, 0xf7]))).toBeNull();
  expect(parseDeviceMessage(u8([0xf0, 0x7d, 0x42, 0x01, 0x10, 0x00, 0x16, 0xf7]))).toBeNull();
  expect(parseDeviceMessage(u8([0xf0, 0x7d, 0x42, 0x01, 0x11, 0x01, 0xf7]))).toBeNull();
  expect(parseDeviceMessage(u8([0xf0, 0x7d, 0x42, 0x01, 0x12, 0x68]))).toBeNull();
  expect(parseDeviceMessage(u8([0xf0, 0x7d, 0x42, 0x01, 0x7f, 0xf7]))).toBeNull();
});

