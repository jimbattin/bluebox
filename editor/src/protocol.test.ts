test("ROM encoders", () => {
  expect(romBegin(3)).toEqual([0xf0, 0x7d, 0x42, 0x01, 0x07, 0x03, 0xf7]);
  expect(romErase(10)).toEqual([0xf0, 0x7d, 0x42, 0x01, 0x0a, 0x0a, 0xf7]);
  expect(romCommit(3, 0x9b2559af)).toEqual([0xf0, 0x7d, 0x42, 0x01, 0x09, 0x03, 0x09, 0x59, 0x15, 0x33, 0x2f, 0xf7]);
  const chunk = Uint8Array.from({ length: 64 }, (_, i) => (i * 3) & 0xff);
  const f = romData(0, 64, chunk);
  expect(f.length).toBe(137);
  expect(f.slice(0, 14)).toEqual([0xf0, 0x7d, 0x42, 0x01, 0x08, 0x00, 0x00, 0x40, 0x00, 0x00, 0x00, 0x03, 0x00, 0x06]);
  expect(f[136]).toBe(0xf7);
  expect(f[5 + 3 + 2 * 43]).toBe(1); // chunk[43] = 129: high bit set
});

test("parse ROM_ACK / ROM_RESULT", () => {
  expect(parseDeviceMessage(u8([0xf0, 0x7d, 0x42, 0x01, 0x14, 0x0a, 0x20, 0x00, 0xf7]))).toEqual({
    kind: "romAck",
    slot: 10,
    next: 4096,
  });
  expect(parseDeviceMessage(u8([0xf0, 0x7d, 0x42, 0x01, 0x15, 0x00, 0x04, 0xf7]))).toEqual({
    kind: "romResult",
    slot: 0,
    code: 4,
  });
  expect(parseDeviceMessage(u8([0xf0, 0x7d, 0x42, 0x01, 0x14, 0x0a, 0x20, 0xf7]))).toBeNull();
});

test("parse ROMS", () => {
  const head = [
    0xf0, 0x7d, 0x42, 0x01, 0x13, 0x01, 0x02, 0x01, 0x75, 0x2d, 0x2c, 0x7e, 0x02, 0x05, 0x1a, 0x26, 0x67, 0x07, 0x02,
    0x08, 0x0f, 0x64, 0x4f, 0x75,
  ];
  const m = parseDeviceMessage(u8([...head, ...new Array(48).fill(0), 0xf7]));
  expect(m?.kind).toBe("roms");
  if (m?.kind !== "roms") return;
  expect(m.embedded).toBe(true);
  expect(m.slots.length).toBe(11);
  expect(m.slots.slice(0, 3)).toEqual([
    { state: 2, crc: 0x1eab567e },
    { state: 2, crc: 0x5349b387 },
    { state: 2, crc: 0x81f927f5 },
  ]);
  for (const s of m.slots.slice(3)) expect(s).toEqual({ state: 0, crc: 0 });
  expect(parseDeviceMessage(u8([...head, ...new Array(47).fill(0), 0xf7]))).toBeNull();
});
